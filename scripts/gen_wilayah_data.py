def norm(name: str) -> str:
    s = name.lower().replace("&", "dan")
    s = re.sub(r"\b(kab\.|kabupaten|kota administrasi|adm\.|kota|kab)\b", " ", s)
    s = unicodedata.normalize("NFKD", s)
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")


